    console.log('     let encrypted = cipher.update(plaintext, "utf8", "hex");');
    console.log('     encrypted += cipher.final("hex");');
    console.log('     return iv.toString("hex") + ":" + encrypted;');
    console.log('   }');
    console.log('   ');
    console.log('   export function decryptKey(ciphertext: string): string {');
    console.log('     const [ivHex, encryptedHex] = ciphertext.split(":");');
    console.log('     const iv = Buffer.from(ivHex, "hex");');
    console.log('     const decipher = crypto.createDecipheriv(ALGORITHM, KEY, iv);');
    console.log('     let decrypted = decipher.update(encryptedHex, "hex", "utf8");');
    console.log('     decrypted += decipher.final("utf8");');
    console.log('     return decrypted;');
    console.log('   }');
    console.log('   ```');
